#!/usr/bin/env node
/**
 * Generate `samples-catalog/catalog.spec.json` from the vendored AndroidX Wear Remote Compose
 * Material 3 samples under `samples-catalog/src/main/kotlin/upstream/`.
 *
 * The inventory is generated rather than annotated with `@CatalogComponent` because the vendored
 * files are upstream's bytes, re-fetched byte-identically on every `scripts/import-samples.mjs`
 * run.
 *
 *     node scripts/samples-spec.mjs          # regenerate samples-catalog/catalog.spec.json
 *     node scripts/samples-spec.mjs --check  # fail if the committed spec differs
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, relative } from "node:path";

const SAMPLES_ROOT = "samples-catalog";
const UPSTREAM_DIR = join(
  SAMPLES_ROOT,
  "src/main/kotlin/upstream/androidx/wear/compose/remote/material3/samples",
);
const QUARANTINE_FILE = "samples/quarantine.json";
const SPEC_FILE = join(SAMPLES_ROOT, "catalog.spec.json");

function readQuarantinedPreviews() {
  try {
    const data = JSON.parse(readFileSync(QUARANTINE_FILE, "utf8"));
    return new Set(
      (data.previews ?? []).map((p) => (typeof p === "string" ? p : p.name || p.preview)),
    );
  } catch {
    return new Set();
  }
}

function groupNameForFile(fileName) {
  return fileName.replace(/Samples?\.kt$/, "");
}

function scanSampleFile(filePath, quarantinedPreviews) {
  const text = readFileSync(filePath, "utf8");
  const lines = text.split(/\r?\n/);
  const entries = [];

  for (let i = 0; i < lines.length; i++) {
    const match = lines[i].match(/^\s*(?:public\s+)?fun\s+([A-Za-z0-9_]+)\s*\(/);
    if (!match) continue;
    const fnName = match[1];
    // Look up to 8 lines above for @WearPreviewDevices or @Preview
    const header = lines.slice(Math.max(0, i - 8), i).join("\n");
    if (!/@(?:WearPreviewDevices|Preview)\b/.test(header)) continue;
    if (quarantinedPreviews.has(fnName)) continue;

    entries.push({
      name: fnName,
      line: i + 1,
    });
  }
  return entries;
}

export function buildSpec() {
  const quarantinedPreviews = readQuarantinedPreviews();
  const files = readdirSync(UPSTREAM_DIR)
    .filter((f) => f.endsWith(".kt"))
    .sort();

  const groups = [];
  let totalComponents = 0;

  for (const file of files) {
    const absPath = join(UPSTREAM_DIR, file);
    const groupName = groupNameForFile(file);
    const samples = scanSampleFile(absPath, quarantinedPreviews);
    if (samples.length === 0) continue;

    const sourceFile = relative(SAMPLES_ROOT, absPath).replace(/\\/g, "/");
    const components = samples.map((s) => ({
      componentId: `${groupName}/${s.name}`,
      preview: s.name,
      caption: `${s.name} — upstream AndroidX sample for \`${groupName}\`.`,
      sourceFile,
      bodyLine: s.line,
    }));
    totalComponents += components.length;
    groups.push({ name: groupName, components });
  }

  return {
    spec: {
      $schema:
        "https://raw.githubusercontent.com/yschimke/compose-ai-tools/main/scripts/design-artifacts/catalog.spec.schema.json",
      $comment:
        "GENERATED by scripts/samples-spec.mjs from the vendored sources — do not edit. The inventory is generated rather than annotated because the sources are upstream's bytes, re-fetched byte-identically on every import.",
      system: "remote-m3-samples",
      title: "Remote Wear Material 3 Samples",
      library: ["androidx.wear.compose.remote:remote-material3"],
      module: ":samples-catalog",
      modes: ["dark"],
      display: {
        role: "samples",
      },
      compareWith: {
        system: "remote-m3",
        spec: "../remote-catalog/catalog.spec.json",
      },
      groups,
    },
    totalComponents,
    groupCount: groups.length,
  };
}

const check = process.argv.includes("--check");
const { spec, totalComponents, groupCount } = buildSpec();
const rendered = `${JSON.stringify(spec, null, 2)}\n`;

if (check) {
  let current = "";
  try {
    current = readFileSync(SPEC_FILE, "utf8");
  } catch {
    console.error(`${SPEC_FILE} is missing. Run: node scripts/samples-spec.mjs`);
    process.exit(1);
  }
  if (current !== rendered) {
    console.error(`${SPEC_FILE} is out of date. Run: node scripts/samples-spec.mjs`);
    process.exit(1);
  }
  console.log(`${SPEC_FILE} is current (${totalComponents} component(s) in ${groupCount} group(s)).`);
} else {
  writeFileSync(SPEC_FILE, rendered);
  console.log(`${SPEC_FILE}: ${totalComponents} component(s) in ${groupCount} group(s).`);
}
